#!/usr/bin/env python3
"""Generate all pac maze levels with validated grids."""
import json
from pathlib import Path

OUT = Path(__file__).parent


def r(s: str, w: int) -> str:
    if len(s) != w:
        raise ValueError(f"len {len(s)} != {w}: {s!r}")
    return s


def save(d):
    w, h = d["width"], d["height"]
    for i, row in enumerate(d["grid"]):
        r(row, w)
    if len(d["grid"]) != h:
        raise ValueError(f"rows {len(d['grid'])} != height {h}")
    path = OUT / f"level_{d['id']:03d}.json"
    path.write_text(json.dumps(d, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    print("ok", path.name)


