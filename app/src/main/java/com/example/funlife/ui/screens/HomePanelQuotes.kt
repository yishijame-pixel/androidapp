    /**
     * 根据 userId + 当前日期 选一句。
     * userId<=0（未登录）时退化为"全员同款"。
     */
    fun quoteFor(userId: Long, date: LocalDate = LocalDate.now()): String {
        if (QUOTES.isEmpty()) return "今天也要开开心心 ✨"
        val seed = (date.toEpochDay() + userId.coerceAtLeast(0L) * 31L)
        // 哈希一下避免相邻日期对相同 userId 总是相邻索引
        val mixed = (seed * 2654435761L) xor (seed shr 16)
        val idx = ((mixed % QUOTES.size) + QUOTES.size) % QUOTES.size
        return QUOTES[idx.toInt()]
    }

    /** 是否应该把这条文字视为"未自定义" → 显示每日语录 */
    fun shouldUseDailyQuote(text: String?): Boolean {
        if (text.isNullOrBlank()) return true
        return text.trim() in LEGACY_PLACEHOLDERS
    }
